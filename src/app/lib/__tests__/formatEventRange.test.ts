import { describe, expect, it } from "vitest";
import { formatEventRange } from "../formatEventRange";

describe("formatEventRange", () => {
  it.each([
    ["2026-10-09", "2026-10-10", "2026/10/09〜2026/10/10"],
    ["2026-12-31", "2027-01-02", "2026/12/31〜2027/01/02"],
    ["2026-10-10", "", "2026/10/10"],
    ["2026-10-10", "2026-10-10", "2026/10/10"],
    ["2026-10-10", "invalid", "2026/10/10"],
    ["2026-10-09T15:00:00.000Z", "2026-10-10T14:59:59.999Z", "2026/10/10"],
    [
      "2026-10-10T14:59:59.999Z",
      "2026-10-10T15:00:00.000Z",
      "2026/10/10〜2026/10/11",
    ],
  ])("日本時間の開催日を表示する: %s - %s", (start, end, expected) => {
    expect(formatEventRange(start, end, "ja")).toBe(expected);
  });

  it("英語の開催期間も日本時間で表示する", () => {
    expect(
      formatEventRange(
        "2026-10-10T14:59:59.999Z",
        "2026-10-10T15:00:00.000Z",
        "en",
      ),
    ).toBe("Oct 10, 2026 - Oct 11, 2026");
  });

  it.each([
    ["2026-10-09", "2026-10-12", "2026/10/09〜10/12"],
    ["2026-10-31", "2026-11-02", "2026/10/31〜11/02"],
    ["2026-12-31", "2027-01-02", "2026/12/31〜2027/01/02"],
    ["2026-10-10", "2026-10-10", "2026/10/10"],
    [
      "2026-12-31T14:59:59.999Z",
      "2026-12-31T15:00:00.000Z",
      "2026/12/31〜2027/01/01",
    ],
  ])("短縮表示では同じ年の繰り返しを省く: %s - %s", (start, end, expected) => {
    expect(formatEventRange(start, end, "ja", { compact: true })).toBe(
      expected,
    );
  });

  it("英語の短縮表示でも同じ年を省く", () => {
    expect(
      formatEventRange("2026-10-09", "2026-10-12", "en", { compact: true }),
    ).toBe("Oct 9, 2026 - Oct 12");
  });
});
